/* Generate content/manifest.js from the registered unit files.
   The manifest carries only the metadata the cover, rail and router need, so a
   unit page can defer every other unit's prose and widgets.

     node scripts/build_manifest.mjs

   Run after editing content/units. scripts/lint_content.py fails when the
   shipped manifest and the unit files disagree. */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const data = JSON.parse(execFileSync('node', [path.join(root, 'scripts', 'extract_units.mjs'), root], { encoding: 'utf8' }));
const contentFiles = readdirSync(path.join(root, 'content', 'units')).filter(f => f.endsWith('.js'));
const widgetFiles = readdirSync(path.join(root, 'js', 'widgets')).filter(f => /^\d\d-/.test(f));
const widgetOwner = {};
for (const wf of widgetFiles) {
  const src = readFileSync(path.join(root, 'js', 'widgets', wf), 'utf8');
  for (const m of src.matchAll(/AIM\.register\('([a-z0-9-]+)'/g)) widgetOwner[m[1]] = 'js/widgets/' + wf;
}

const entries = data.units.sort((a, b) => a.n - b.n).map(u => {
  const nn = String(u.n).padStart(2, '0');
  const file = contentFiles.find(f => f.startsWith(nn + '-'));
  const widget = widgetFiles.find(f => f.startsWith(nn + '-'));
  if (!file || !widget) throw new Error(`unit ${u.n}: missing content or widget file`);
  const own = 'js/widgets/' + widget;
  const ids = u.concepts.reduce((list, c) => list.concat(
    ['metaphor', 'mechanism', 'sandbox'].map(k => c[k] && c[k].widget).filter(Boolean)
  ), []);
  const extraWidgets = Array.from(new Set(ids.map(id => widgetOwner[id]).filter(f => f && f !== own))).sort();
  return {
    n: u.n,
    hue: u.hue,
    short: u.short,
    title: u.title,
    weeks: u.weeks,
    promise: u.promise,
    minutes: u.minutes,
    lectures: u.lectures,
    interactions: u.concepts.reduce((n, c) => n + 2 + (c.mechanism ? 1 : 0) + (c.sandbox ? 1 : 0), 0),
    concepts: u.concepts.map(c => ({ id: c.id, title: c.title, checks: c.check.length })),
    file: 'content/units/' + file,
    widget: own,
    extraWidgets
  };
});

const out = path.join(root, 'content', 'manifest.js');
writeFileSync(out,
  '/* Generated by scripts/build_manifest.mjs. Do not edit by hand. */\n' +
  'AIM.registerManifest(' + JSON.stringify(entries) + ');\n');
console.log(`manifest: ${entries.length} units, ${entries.reduce((n, u) => n + u.concepts.length, 0)} concepts, ${statSync(out).size} bytes`);
